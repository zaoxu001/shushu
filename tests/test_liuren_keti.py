def test_book_examples_hit_their_keti():
    for name, ge, gz, yj, zs in CASES:
        hits = detect_parts(gz, yj, zs, zs in DAY)
        assert any(h["name"] == name and (not ge or h["ge"] == ge) for h in hits), (name, ge, gz, yj, zs, hits)


def test_every_hit_cites_the_book():
    for _, _, gz, yj, zs in CASES:
        for h in detect_parts(gz, yj, zs, zs in DAY):
            assert h["vol"] in (5, 6, 7, 8) and h["text"]
